#!/usr/bin/env python
"""HTTP client tests against the mock EverRoom Gateway."""

from __future__ import annotations

import pytest

from metagit.core.integrations.everroom.client import EverRoomHttpClient, markdown_to_tiptap
from metagit.core.integrations.everroom.errors import (
    EverRoomAuthError,
    EverRoomInvalidResponseError,
    EverRoomNotFoundError,
    EverRoomUnavailableError,
)
from tests.core.integrations.everroom.mock_gateway import (
    ROOM_ID,
    SECRET_TOKEN,
    MockGatewayState,
    start_mock_gateway,
)


def test_health_success() -> None:
    gateway = start_mock_gateway()
    try:
        client = EverRoomHttpClient(endpoint=gateway.url, token=SECRET_TOKEN)
        health = client.health()
        assert health.status == "ok"
        assert health.service == "nxcore-gateway"
    finally:
        gateway.stop()


def test_authentication_failure_does_not_echo_token() -> None:
    gateway = start_mock_gateway()
    try:
        client = EverRoomHttpClient(endpoint=gateway.url, token="wrong-token")
        with pytest.raises(EverRoomAuthError) as exc:
            client.resolve_room(ROOM_ID)
        assert SECRET_TOKEN not in str(exc.value)
        assert "METAGIT_EVERROOM_TOKEN" in exc.value.message
    finally:
        gateway.stop()


def test_missing_token_fails_before_request() -> None:
    gateway = start_mock_gateway()
    try:
        client = EverRoomHttpClient(endpoint=gateway.url, token="")
        with pytest.raises(EverRoomAuthError) as exc:
            client.resolve_room(ROOM_ID)
        assert "METAGIT_EVERROOM_TOKEN" in exc.value.message
    finally:
        gateway.stop()


def test_room_lookup_success() -> None:
    gateway = start_mock_gateway()
    try:
        client = EverRoomHttpClient(endpoint=gateway.url, token=SECRET_TOKEN)
        room = client.resolve_room(ROOM_ID)
        assert room.id == ROOM_ID
        assert room.title == "terraform-hcp-migration"
        sources = client.list_room_sources(ROOM_ID)
        documents = client.list_room_documents(ROOM_ID)
        decisions = client.list_room_decisions(ROOM_ID, limit=10)
        context = client.get_room_context(ROOM_ID)
        assert len(sources) == 4
        assert len(documents) == 2
        assert len(decisions) == 3
        assert len(context.next_steps) == 2
    finally:
        gateway.stop()


